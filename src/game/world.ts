export function createWorld(zoneId = START_ZONE_ID, classId: PlayerClassId = 'warrior'): World {
  const zone = ZONES[zoneId] ?? ZONES[START_ZONE_ID];
  const starter = createStarterInventory(classId);
  const dummies = zone.spawns.map((spawn, i) =>
    createDummyFromSpawn(i + 1, spawn.enemyId, spawn.x, spawn.y, spawn.patrolMin, spawn.patrolMax),
  );
  const world: World = {
    zoneId: zone.id,
    platforms: zonePlatforms(zone),
    rivers: zone.rivers.map((r) => ({ ...r })),
    banners: zone.banners.map((b) => ({ ...b })),
    player: createPlayer(classId),
    dummyId: dummies.length,
    hazards: [],
    hazardId: 0,
    projectiles: [],
    projectileId: 0,
    traps: [],
    trapId: 0,
    blizzards: [],
    blizzardId: 0,
    popups: [],
    popupId: 0,
    dusts: [],
    dustId: 0,
    lootFlies: [],
    lootFlyId: 0,
    loots: [],
    lootId: 0,
    gold: starter.gold,
    bag: starter.bag,
    itemUid: starter.itemUid,
    mainhandUid: starter.bag[0]?.uid ?? null,
    invOpen: false,
    charOpen: false,
    skillOpen: false,
    catalogOpen: false,
    settingsOpen: false,
    levelUpOpen: false,
    levelUpGainAttr: 0,
    levelUpGainSkill: 0,
    campOpen: null,
    nearbyCamp: null,
    campMessage: '',
    nearbyHubPortal: false,
    unlockedZones: defaultUnlockedZones(),
    attrDraft: { str: 0, agi: 0, int: 0, vit: 0, spi: 0 },
    skills: createStarterSkills(classId),
    skillBar: createStarterSkillBar(classId),
    specId: null,
    specPickOpen: false,
    specNodes: {},
    specNodePickTier: null,
    nearbyLootName: null,
    nearbyLootCompare: null,
    nearbyLootTone: null,
    secretsClaimed: {},
    nearbySecretId: null,
    bossKills: {},
    ngPlusLevel: 0,
    challengeActive: false,
    challengeT: 0,
    challengeFloor: 0,
    challengeBestFloor: 0,
    challengeRunAffixes: [],
    discoveredLegendaries: [],
    tutorialStep: 'move',
    tutorialDone: false,
    tutorialAttrHint: false,
    tutorialSkillHint: false,
    breakables: createBreakablesFromZone(zone.id),
    kitTheme: zone.theme,
    shake: 0,
    levelToastT: 0,
    levelToastText: '',
    zoneAnnounceT: 0,
    zoneAnnounceName: '',
    zoneAnnounceSub: '',
    offerNgPlusHint: false,
    bossGateClosed: false,
    bossGateX: 0,
    slowMoT: 0,
    exploreTrail: [],
    dummies,
  };
  applyGearStats(world.player, world);
  return world;
}
