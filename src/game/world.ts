import { START_ZONE_ID, ZONES, zonePlatforms } from './data/zones';
import { CLASS_DEFS, type PlayerClassId } from './data/classes';
import { createStarterInventory, applyGearStats } from './systems/inventory';
import { createDummyFromSpawn } from './systems/enemy-spawn';
